export function flagOf(ioc: string): string | null {
  const iso = IOC_TO_ISO[ioc.toUpperCase()];
  if (!iso) return null;
  return String.fromCodePoint(...[...iso].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}
