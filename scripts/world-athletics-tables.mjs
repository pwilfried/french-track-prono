// #428: imports the World Athletics scoring tables (the « Hungarian » tables) into
// src/domain/world-athletics-tables.ts, the versioned copy the domain reads. The tables are only
// published as lookup books; their coefficients come from the MIT-licensed GlaivePro/IaafPoints
// library, pinned to a commit so a run always writes the same file. The PHP file is read as data,
// never executed.
//
//   node scripts/world-athletics-tables.mjs            # fetch the pinned commit
//   node scripts/world-athletics-tables.mjs path.php   # read a local copy instead
//
// A new edition: change EDITION and COMMIT, run the script, check the reference values in
// src/domain/world-athletics-points.test.ts against the book, commit the regenerated file.
import { readFile, writeFile } from "node:fs/promises";

const EDITION = "2025";
const COMMIT = "b10d611976a3e87ed612deb4f30483f1df8c80de";
const SOURCE = `https://github.com/GlaivePro/IaafPoints/blob/${COMMIT}/resources/iaaf/${EDITION}.php`;
const RAW = `https://raw.githubusercontent.com/GlaivePro/IaafPoints/${COMMIT}/resources/iaaf/${EDITION}.php`;
const OUTPUT = new URL("../src/domain/world-athletics-tables.ts", import.meta.url);

/** The tokens of the PHP subset the tables are written in. */
function tokenize(php) {
  const tokens = [];
  const pattern =
    /\s+|<\?php|\/\*[\s\S]*?\*\/|\/\/[^\n]*|'([^']*)'|(-?\d+(?:\.\d+)?(?:e-?\d+)?)|\$(\w+)|(return)|(=>|[[\],=;])/gy;
  while (pattern.lastIndex < php.length) {
    const at = pattern.lastIndex;
    const match = pattern.exec(php);
    if (!match) throw new Error(`unreadable PHP at ${php.slice(at, at + 40)}`);
    const [, string, number, variable, keyword, symbol] = match;
    if (string !== undefined) tokens.push({ type: "string", value: string });
    else if (number !== undefined) tokens.push({ type: "number", value: Number(number) });
    else if (variable !== undefined) tokens.push({ type: "variable", value: variable });
    else if (keyword !== undefined) tokens.push({ type: "return" });
    else if (symbol !== undefined) tokens.push({ type: symbol });
  }
  return tokens;
}

/** The array the file returns, with its `$variable['key']` references resolved. */
function parse(php) {
  const tokens = tokenize(php);
  const variables = {};
  let at = 0;
  const next = () => tokens[at++];
  const expect = (type) => {
    const token = next();
    if (token?.type !== type) throw new Error(`expected ${type}, got ${token?.type}`);
    return token;
  };
  const value = () => {
    const token = next();
    if (token.type === "number" || token.type === "string") return token.value;
    if (token.type === "variable") {
      let resolved = variables[token.value];
      while (tokens[at]?.type === "[") {
        next();
        resolved = resolved[expect("string").value];
        expect("]");
      }
      if (resolved === undefined) throw new Error(`unknown reference $${token.value}`);
      return resolved;
    }
    if (token.type !== "[") throw new Error(`unexpected ${token.type}`);
    const array = {};
    while (tokens[at].type !== "]") {
      const key = expect("string").value;
      expect("=>");
      array[key] = value();
      if (tokens[at].type === ",") next();
    }
    next();
    return array;
  };
  while (at < tokens.length) {
    const token = next();
    if (token.type === "return") {
      const result = value();
      expect(";");
      return result;
    }
    if (token.type !== "variable") throw new Error(`unexpected ${token.type}`);
    expect("=");
    variables[token.value] = value();
    expect(";");
  }
  throw new Error("the file returns nothing");
}

function render(tables) {
  const lines = [
    `// Generated by scripts/world-athletics-tables.mjs (#428): do not edit by hand.`,
    `// World Athletics scoring tables, ${EDITION} edition. Coefficients from GlaivePro/IaafPoints`,
    `// (MIT licence), ${SOURCE}`,
    `// points = floor(factor × (mark + shift)² + offset); mark in seconds, metres or points.`,
    ``,
    `export type ScoringCoefficients = { shift: number; factor: number; offset: number };`,
    ``,
    `export const WORLD_ATHLETICS_EDITION = "${EDITION}";`,
    ``,
    `/** Coefficients by sex, then by World Athletics event key ("100m", "high_jump"…). */`,
    `export const WORLD_ATHLETICS_TABLES: Record<"F" | "M", Record<string, ScoringCoefficients>> = {`,
  ];
  for (const [sex, key] of [
    ["F", "f"],
    ["M", "m"],
  ]) {
    lines.push(`  ${sex}: {`);
    for (const [event, c] of Object.entries(tables[key])) {
      const name = /^[a-z_]\w*$/i.test(event) ? event : JSON.stringify(event);
      lines.push(
        `    ${name}: { shift: ${c.resultShift}, factor: ${c.conversionFactor}, offset: ${c.pointShift} },`,
      );
    }
    lines.push(`  },`);
  }
  lines.push(`};`, ``);
  return lines.join("\n");
}

async function main() {
  const local = process.argv[2];
  const php = local
    ? await readFile(local, "utf8")
    : await fetch(RAW).then((r) => {
        if (!r.ok) throw new Error(`${RAW} answered ${r.status}`);
        return r.text();
      });
  const tables = parse(php);
  await writeFile(OUTPUT, render(tables));
  const count = Object.keys(tables.f).length + Object.keys(tables.m).length;
  console.log(`${count} tables written to src/domain/world-athletics-tables.ts.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
